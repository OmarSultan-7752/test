"""قاعدة حرف الجواب: الكلمة الوصفية في أول الجواب (قناة، جبل، نهر…) ما تُحسب، والحرف يؤخذ من الاسم اللي بعدها."""
HAMZA = str.maketrans({"أ": "ا", "إ": "ا", "آ": "ا"})
# تُهمل لو جت أول الجواب بدون "ال" (قناة السويس، جبل طارق…)
GENERIC = {"قناة", "جبل", "جزر", "جزيرة", "نهر", "بحر", "مضيق", "خليج", "سورة", "غزوة", "معركة", "مسجد",
           "جامعة", "برج", "وادي", "سور", "سد", "شلالات", "غابة", "تلسكوب", "قانون", "لوحة", "يوم", "ليلة",
           "بيعة", "صلح", "حجر", "طريق"}
# تُهمل حتى لو بـ"ال"
GENERIC_AL = {"الدولة", "المسجد", "الجامعة"}


def key_word(answer):
    w = answer.strip().split()
    if len(w) >= 2 and (w[0] in GENERIC or w[0] in GENERIC_AL):
        w = w[1:]
    return w[0]


def first_letter(answer):
    a = key_word(answer)
    if a.startswith("ال") and len(a) > 3:
        a = a[2:]
    return a[0].translate(HAMZA)
